export function resolveLocale(savedLocale, browserLanguages = []) {
  if (supportedLocales.includes(savedLocale)) return savedLocale;
  const languages = Array.isArray(browserLanguages) ? browserLanguages : [];
  return languages.some((language) => language.toLowerCase().startsWith("zh"))
    ? "zh-CN"
    : "en-US";
}

export function translate(locale, key, variables = {}) {
  const template = messages[locale]?.[key] ?? messages["en-US"][key] ?? key;
  return Object.entries(variables).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    template,
  );
}

export function createFormatters(locale) {
  return {
    compactNumber: new Intl.NumberFormat(locale, {
      notation: "compact",
      maximumFractionDigits: 2,
    }),
    integerNumber: new Intl.NumberFormat(locale, { maximumFractionDigits: 0 }),
    moneyNumber: new Intl.NumberFormat(locale, {
      style: "currency",
      currency: "USD",
      minimumFractionDigits: 2,
      maximumFractionDigits: 6,
    }),
    dateTime: new Intl.DateTimeFormat(locale, {
      month: "2-digit",
      day: "2-digit",
      hour: "2-digit",
      minute: "2-digit",
      second: "2-digit",
    }),
  };
}
